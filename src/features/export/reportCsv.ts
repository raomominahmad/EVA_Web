export const REPORT_CSV_HEADER = [
  'Section',
  'Item',
  'Symbol',
  'Value',
  'Display value',
  'Unit',
  'Formula or definition',
  'Interpretation',
] as const;

/** Metric sections in report order (`UI_WORKFLOW.md` §6). */
export const METRIC_SECTIONS: readonly { title: string; metrics: readonly MetricKey[] }[] = [
  { title: 'Cost performance', metrics: ['cv', 'cpi'] },
  { title: 'Schedule performance', metrics: ['sv', 'spi'] },
  { title: 'Progress', metrics: ['plannedCompletion', 'earnedCompletion', 'budgetUtilization'] },
  { title: 'Forecast', metrics: ['eac', 'etc', 'vac', 'tcpiBac', 'tcpiEac'] },
];

const PERCENT_UNIT = '% of BAC';

interface Row {
  section: string;
  item: string;
  symbol?: string | null;
  value: CsvCell;
  display?: string;
  unit?: string;
  definition?: string;
  interpretation?: string;
}

function toCells(row: Row): CsvCell[] {
  return [
    text(row.section),
    text(row.item),
    text(row.symbol ?? ''),
    row.value,
    text(row.display ?? ''),
    text(row.unit ?? ''),
    text(row.definition ?? ''),
    text(row.interpretation ?? ''),
  ];
}

function valueCell(value: number | MetricResult): CsvCell {
  if (typeof value === 'number') return number(value);
  return value.status === 'defined' ? number(value.value) : text(NOT_AVAILABLE);
}

function display(unit: MetricUnit, value: number | MetricResult, analysis: Analysis): string {
  if (unit === 'currency') return formatCurrency(value, analysis.currency);
  return unit === 'index' ? formatRatio(value) : formatPercent(value);
}

function unitLabel(unit: MetricUnit, analysis: Analysis): string {
  if (unit === 'currency') return analysis.currency;
  return unit === 'index' ? 'Ratio' : PERCENT_UNIT;
}

export const AI_SECTION = 'AI-generated summary';

/**
 * AI rows (FR-25, `UI_WORKFLOW.md` §8.4): only for a summary of exactly these confirmed inputs.
 * Every row is in the "AI-generated summary" section, carries no number, and keeps the AI text in
 * the interpretation column, so it can never be read as a calculated metric.
 */
function aiSummaryRows(analysis: Analysis, summary: AiSummaryResponse | null): Row[] {
  if (
    !summary ||
    summary.inputFingerprint !== inputFingerprint(analysis.currency, analysis.inputs)
  ) {
    return [];
  }
  const evidence = (item: AiSummaryItem) =>
    `Evidence: ${item.evidence.map((key) => describeEvidence(key, analysis).label).join(', ')}.`;
  const items = (label: string, list: readonly AiSummaryItem[]): Row[] =>
    list.map((item, index) => ({
      section: AI_SECTION,
      item: `${label} ${index + 1}`,
      value: text(''),
      definition: evidence(item),
      interpretation: item.text,
    }));

  return [
    {
      section: AI_SECTION,
      item: 'Notice',
      value: text(''),
      definition:
        'Generated by an AI model from the calculated results. Not a calculated EVA metric; it may be incomplete or wrong. The calculated values above are authoritative.',
    },
    { section: AI_SECTION, item: 'Model', value: text(summary.modelLabel) },
    { section: AI_SECTION, item: 'Generated at', value: text(summary.generatedAt) },
    {
      section: AI_SECTION,
      item: 'Summary',
      value: text(''),
      interpretation: summary.content.summary,
    },
    ...summary.content.observations.map((observation, index) => ({
      section: AI_SECTION,
      item: `Observation ${index + 1}`,
      value: text(ASSESSMENT_LABELS[observation.assessment]),
      definition: evidence(observation),
      interpretation: observation.text,
    })),
    ...items('Cost risk', summary.content.costRisks),
    ...items('Recommendation', summary.content.recommendations),
    ...items('Limitation', summary.content.limitations),
  ];
}

/**
 * All report rows, built only from the shared analysis result and the project details, plus the
 * AI summary when one exists for these confirmed inputs.
 */
export function buildReportRows(
  analysis: Analysis,
  project: ProjectDetails,
  aiSummary: AiSummaryResponse | null = null,
): CsvCell[][] {
  const rows: Row[] = [];
  const reportingDate = formatReportingDate(project.reportingDate);
  const currencyName = SUPPORTED_CURRENCIES.find((item) => item.code === analysis.currency)?.name;
  const notProvided = 'Not provided';

  rows.push(
    { section: 'Project', item: 'Project name', value: text(project.name.trim()) },
    {
      section: 'Project',
      item: 'Description',
      value: text(project.description.trim() || notProvided),
    },
    {
      section: 'Project',
      item: 'Project manager',
      value: text(project.manager.trim() || notProvided),
    },
    {
      section: 'Project',
      item: 'Reporting date',
      value: text(reportingDate ? project.reportingDate : notProvided),
      display: reportingDate ?? notProvided,
    },
    {
      section: 'Project',
      item: 'Currency',
      value: text(analysis.currency),
      display: currencyName ? `${analysis.currency} (${currencyName})` : analysis.currency,
      definition: 'All amounts are in this currency. No conversion is applied.',
    },
  );

  const summary = summarizePerformance(analysis);
  rows.push(
    {
      section: 'Summary',
      item: 'Cost performance',
      value: text(summary.cost.label),
      definition: 'Based on CPI.',
      interpretation: summary.cost.text,
    },
    {
      section: 'Summary',
      item: 'Schedule performance',
      value: text(summary.schedule.label),
      definition: 'Based on SPI.',
      interpretation: summary.schedule.text,
    },
  );

  for (const field of EVA_INPUT_FIELDS) {
    const { symbol, name, definition } = EVA_INPUT_DEFINITIONS[field];
    rows.push({
      section: 'Inputs',
      item: name,
      symbol,
      value: number(analysis.inputs[field]),
      display: formatCurrency(analysis.inputs[field], analysis.currency),
      unit: analysis.currency,
      definition,
      interpretation: 'User-entered value.',
    });
  }

  for (const { title, metrics } of METRIC_SECTIONS) {
    for (const key of metrics) {
      const definition = METRIC_DEFINITIONS[key];
      const value = analysis.metrics[key];
      rows.push({
        section: title,
        item: definition.name,
        symbol: definition.symbol,
        value: valueCell(value),
        display: display(definition.unit, value, analysis),
        unit: unitLabel(definition.unit, analysis),
        definition: `${definition.formula}. ${definition.definition}`,
        interpretation: interpretMetric(key, analysis).text,
      });
    }
  }

  const { budget } = analysis;
  const section = 'Budget versus actual';
  const budgetRow = (
    key: keyof typeof BUDGET_DEFINITIONS,
    value: number | MetricResult,
    unit: MetricUnit,
    interpretation: string,
  ): Row => ({
    section,
    item: BUDGET_DEFINITIONS[key].name,
    value: valueCell(value),
    display: display(unit, value, analysis),
    unit: unitLabel(unit, analysis),
    definition: `${BUDGET_DEFINITIONS[key].formula}. ${BUDGET_DEFINITIONS[key].definition}`,
    interpretation,
  });
  const budgetInterpretation = interpretBudgetVariance(analysis).text;
  rows.push(
    budgetRow('estimatedCost', budget.estimatedCost, 'currency', 'The approved budget.'),
    budgetRow('actualCost', budget.actualCost, 'currency', 'Spending to date.'),
    budgetRow('budgetVariance', budget.budgetVariance, 'currency', budgetInterpretation),
    budgetRow(
      'budgetVariancePercent',
      budget.budgetVariancePercent,
      'percent',
      budgetInterpretation,
    ),
    { section, item: 'Note', value: text(''), definition: BUDGET_COMPARISON_NOTE },
  );

  ASSUMPTIONS.forEach((assumption, index) => {
    rows.push({
      section: 'Assumptions',
      item: `Assumption ${index + 1}`,
      value: text(''),
      definition: assumption,
    });
  });

  rows.push(...aiSummaryRows(analysis, aiSummary));

  return [REPORT_CSV_HEADER.map(text), ...rows.map(toCells)];
}

/** The CSV report: UTF-8 text with RFC 4180 escaping and CRLF line endings. */
export function buildReportCsv(
  analysis: Analysis,
  project: ProjectDetails,
  aiSummary: AiSummaryResponse | null = null,
): string {
  return serializeCsv(buildReportRows(analysis, project, aiSummary));
}

/** A filesystem-safe name such as `eva-report-billing-platform-2026-03-31.csv`. */
export function reportFileName(project: ProjectDetails): string {
  const slug = project.name
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60)
    .replace(/-+$/g, '');
  const date = formatReportingDate(project.reportingDate) ? `-${project.reportingDate}` : '';
  return `eva-report${slug ? `-${slug}` : ''}${date}.csv`;
}
